/**
 * Generates a synthetic ERP-sized schema view (shaped like RFC 0002 §7.7) plus usage code for one variant.
 * Deterministic: the same (models, seed) always produces the same schema.
 */
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export type Variant = 'none' | 'flat' | 'full';

const SCALAR_TYPES = ['string', 'number', 'boolean', 'Decimal', 'CalendarDate'] as const;

interface ScalarDef {
  readonly name: string;
  readonly type: (typeof SCALAR_TYPES)[number];
  readonly required: boolean;
}
interface M2oDef {
  readonly name: string;
  readonly target: number;
  readonly required: boolean;
}
interface ModelDef {
  readonly scalars: readonly ScalarDef[];
  readonly m2o: readonly M2oDef[];
  readonly x2m: readonly { readonly name: string; readonly target: number }[];
}

/** mulberry32: small, fast, seeded PRNG. */
function prng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const pad = (i: number): string => String(i).padStart(3, '0');
const modelName = (i: number): string => `m${pad(i)}`;

function buildModels(
  count: number,
  seed: number,
  scalarCount: number,
  m2oCount: number,
): ModelDef[] {
  const rnd = prng(seed);
  const pick = (n: number): number => Math.floor(rnd() * n);
  const models: ModelDef[] = [];
  for (let i = 0; i < count; i++) {
    const scalars: ScalarDef[] = [];
    for (let s = 1; s <= scalarCount; s++) {
      const type = SCALAR_TYPES[pick(SCALAR_TYPES.length)] ?? 'string';
      scalars.push({ name: `s${String(s).padStart(2, '0')}`, type, required: rnd() < 0.5 });
    }
    const m2o: M2oDef[] = [];
    for (let r = 1; r <= m2oCount; r++)
      m2o.push({ name: `r${r}`, target: pick(count), required: rnd() < 0.3 });
    models.push({
      scalars,
      m2o,
      x2m: [
        { name: 'l1', target: pick(count) },
        { name: 'l2', target: pick(count) },
        { name: 't1', target: pick(count) },
      ],
    });
  }
  return models;
}

function at<T>(xs: readonly T[], i: number): T {
  const x = xs[i];
  if (x === undefined) throw new Error(`index ${i} out of range`);
  return x;
}

function emitSchema(models: readonly ModelDef[]): string {
  const out: string[] = [
    '// GENERATED by spikes/recordset-types/generate.ts. Do not edit.',
    "import type { CalendarDate, Decimal, Many2one, Scalar, X2many } from '../../src/schema.ts';",
    '',
    'export interface Schema {',
  ];
  models.forEach((_, i) => {
    out.push(`  '${modelName(i)}': M${pad(i)};`);
  });
  out.push('}', '');
  models.forEach((m, i) => {
    out.push(`export interface M${pad(i)} {`, '  readonly fields: {');
    for (const s of m.scalars)
      out.push(`    readonly ${s.name}: Scalar<${s.type}, ${s.required}>;`);
    for (const r of m.m2o)
      out.push(`    readonly ${r.name}: Many2one<'${modelName(r.target)}', ${r.required}>;`);
    for (const x of m.x2m) out.push(`    readonly ${x.name}: X2many<'${modelName(x.target)}'>;`);
    out.push('  };');
    const defaults = [...m.scalars.map((s) => `'${s.name}'`), ...m.m2o.map((r) => `'${r.name}'`)];
    out.push(`  readonly defaults: ${defaults.join(' | ')};`, '}', '');
  });
  return out.join('\n');
}

function tsType(s: ScalarDef): string {
  return s.required ? s.type : `${s.type} | null`;
}

/** One usage function: search, 3-level nested load, typed reads at each level, then a merging load. */
function emitUsage(models: readonly ModelDef[], i: number): string {
  const m = at(models, i);
  const r1 = at(m.m2o, 0);
  const t1 = at(models, r1.target); // target of r1
  const l1 = at(m.x2m, 0);
  const tl = at(models, l1.target); // target of l1 (lines)
  const lr2 = at(tl.m2o, 1);
  const tlr2 = at(models, lr2.target);
  const lr3 = at(tl.m2o, 2);
  const tlr3 = at(models, lr3.target);
  const tlr3r1 = at(models, at(tlr3.m2o, 0).target);
  const t1r2 = at(models, at(t1.m2o, 1).target);
  const v = (def: ModelDef, s: number): ScalarDef => at(def.scalars, s);

  return `
export async function use_${modelName(i)}(env: Env<Schema>): Promise<void> {
  const rs = await env.model('${modelName(i)}').search();
  const a = await rs.load({ r1: ['s01', 's02'], l1: { r2: true, r3: { r1: ['s03'] } } });
  for (const rec of a) {
    const v0: ${tsType(v(m, 0))} = rec.s01;
    const p = rec.r1;
    if (p !== null) {
      const v1: ${tsType(v(t1, 0))} = p.s01;
      const v2: ${tsType(v(t1, 1))} = p.s02;
      void v1; void v2;
    }
    for (const line of rec.l1) {
      const v3: ${tsType(v(tl, 4))} = line.s05;
      const q = line.r2;
      if (q !== null) {
        const v4: ${tsType(v(tlr2, 3))} = q.s04;
        void v4;
      }
      const z = line.r3;
      if (z !== null) {
        const w = z.r1;
        if (w !== null) {
          const v5: ${tsType(v(tlr3r1, 2))} = w.s03;
          void v5;
        }
      }
      void v3;
    }
    void v0;
  }
  const b = await a.load({ r1: { r2: ['s06'] } });
  const pb = b.first().r1;
  if (pb !== null) {
    const v6: ${tsType(v(t1, 0))} = pb.s01;
    const r = pb.r2;
    if (r !== null) {
      const v7: ${tsType(v(t1r2, 5))} = r.s06;
      void v7;
    }
    void v6;
  }
}
`;
}

export interface GenerateOptions {
  readonly dir: string;
  readonly variant: Variant;
  readonly models: number;
  readonly usages: number;
  readonly seed?: number;
  readonly perFile?: number;
  /** Scalar and many2one fields per model (defaults 16 and 5). */
  readonly scalars?: number;
  readonly m2o?: number;
}

/** Writes schema.ts, use_*.ts and tsconfig.json into `dir` (replacing it). Returns the number of files. */
export function generate(opts: GenerateOptions): number {
  const { dir, variant, models: count, usages } = opts;
  const perFile = opts.perFile ?? 25;
  const models = buildModels(count, opts.seed ?? 20261014, opts.scalars ?? 16, opts.m2o ?? 5);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'schema.ts'), emitSchema(models));
  writeFileSync(
    join(dir, 'tsconfig.json'),
    `${JSON.stringify(
      {
        extends: '../../../../tsconfig.base.json',
        compilerOptions: {
          noEmit: true,
          allowImportingTsExtensions: true,
          isolatedDeclarations: false,
          declaration: false,
          declarationMap: false,
        },
        include: ['*.ts'],
      },
      null,
      2,
    )}\n`,
  );
  let files = 1;
  for (let start = 0; start < usages; start += perFile) {
    const body = [
      '// GENERATED. Do not edit.',
      `import type { Env } from '../../src/${variant}.ts';`,
      "import type { Schema } from './schema.ts';",
      "import type { CalendarDate, Decimal } from '../../src/schema.ts';",
      'export type _Unused = CalendarDate | Decimal;',
    ];
    for (let i = start; i < Math.min(start + perFile, usages); i++)
      body.push(emitUsage(models, i % count));
    writeFileSync(join(dir, `use_${pad(start / perFile)}.ts`), body.join('\n'));
    files++;
  }
  return files;
}
